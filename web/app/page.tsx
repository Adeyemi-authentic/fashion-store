async function CategoryTiles() {
  const categories = await getCategories();
  return (
    <ul className="grid grid-cols-2 gap-3 md:grid-cols-3">
      {categories.map((c, i) => (
        <li key={c.slug}>
          <Link href={`/c/${c.slug}`} className="group relative block aspect-[4/5] overflow-hidden rounded-lg bg-sand md:aspect-[4/3]">
            {TILE_IMAGE[c.slug] && (
              <Image
                src={TILE_IMAGE[c.slug]}
                alt=""
                fill
                sizes="(min-width: 768px) 33vw, 50vw"
                quality={70}
                loading={i < 2 ? "eager" : "lazy"}
                fetchPriority={i < 2 ? "high" : "auto"}
                className="object-cover object-top transition-transform duration-500 group-hover:scale-[1.03]"
              />
            )}
            <div className="absolute inset-x-0 bottom-0 bg-gradient-to-t from-ink/75 to-transparent p-3 pt-10 text-cream">
              <span className="font-display text-lg md:text-xl">{categoryLabel(c.slug)}</span>
              <span className="mt-0.5 hidden text-sm opacity-90 md:block">{CATEGORY_INFO[c.slug]?.blurb}</span>
            </div>
          </Link>
        </li>
      ))}
    </ul>
  );
}

async function NewIn() {
  const { items } = await getProducts({ sort: "newest", limit: 8, in_stock: true });
  return (
    <ProductGrid>
      {items.map((p) => (
        <ProductCard key={p.id} product={p} />
      ))}
    </ProductGrid>
  );
}
